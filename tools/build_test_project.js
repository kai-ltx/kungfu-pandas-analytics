#!/usr/bin/env node
// Builds the isolated "PandaMetrics V4 - TEST" Apps Script project into
// build/test/ (gitignored) from apps-script/ sources.
//
// Isolation, enforced here and by tests/js/test_build.test.js:
// - the production spreadsheet id is replaced with the test id and must not
//   appear anywhere in the output;
// - every SpreadsheetApp.openById call is replaced by a guard that only
//   returns the bound (container) spreadsheet, and only if its id is the
//   test id;
// - the manifest requests spreadsheets.currentonly, so the deployed script
//   cannot open any other spreadsheet even if the guard were bypassed.
//
// Config: config/test.local.json (gitignored)
//   { "spreadsheetId": "<test sheet id>", "scriptId": "<test script id>" }
//
// Usage: node tools/build_test_project.js [--config path] [--out dir]

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const SOURCE = path.join(ROOT, "apps-script");
const PRODUCTION_SPREADSHEET_ID = "18tYVaGchByuhKAAAt87q37_8f2_jWtJ75YP4kvEu32c";
const PRODUCTION_SCRIPT_ID = "14BoR7Sd9wECvZgOiiPf2VSNX1d-p4MAdHCGLny5iRABwnSGlQFOpllVe";
const FILES = ["Code.js", "Dashboard.js", "Stats.js", "Index.html", "ClientLib.html"];
const ID_PATTERN = /^[A-Za-z0-9_-]{20,}$/;

const MANIFEST = {
  timeZone: "Europe/London",
  dependencies: {},
  exceptionLogging: "STACKDRIVER",
  runtimeVersion: "V8",
  oauthScopes: ["https://www.googleapis.com/auth/spreadsheets.currentonly"],
  webapp: {
    executeAs: "USER_DEPLOYING",
    access: "ANYONE_ANONYMOUS"
  }
};

function guardSource(testId) {
  return [
    "// GENERATED by tools/build_test_project.js. Test build only.",
    "",
    "const PANDA_TEST_SPREADSHEET_ID = " + JSON.stringify(testId) + ";",
    "",
    "// Stands in for opening a spreadsheet by id. Only the bound test",
    "// spreadsheet is ever returned.",
    "function pandaTestSpreadsheet_(id) {",
    "  if (id !== PANDA_TEST_SPREADSHEET_ID) {",
    "    throw new Error(\"Test build refused a spreadsheet that is not the test spreadsheet\");",
    "  }",
    "  const ss = SpreadsheetApp.getActiveSpreadsheet();",
    "  if (!ss || ss.getId() !== PANDA_TEST_SPREADSHEET_ID) {",
    "    throw new Error(\"Test build is not bound to the test spreadsheet\");",
    "  }",
    "  return ss;",
    "}",
    ""
  ].join("\n");
}

function readConfig(file) {
  if (!fs.existsSync(file)) {
    throw new Error("Missing " + path.relative(ROOT, file) + ". See the header of tools/build_test_project.js.");
  }
  const config = JSON.parse(fs.readFileSync(file, "utf8"));
  return config;
}

function validateConfig(config) {
  const id = config.spreadsheetId;
  if (!id || !ID_PATTERN.test(id)) throw new Error("config spreadsheetId is missing or malformed");
  if (id === PRODUCTION_SPREADSHEET_ID) throw new Error("config spreadsheetId is the PRODUCTION spreadsheet");
  if (config.scriptId !== undefined && config.scriptId !== null) {
    if (!ID_PATTERN.test(config.scriptId)) throw new Error("config scriptId is malformed");
    if (config.scriptId === PRODUCTION_SCRIPT_ID) throw new Error("config scriptId is the PRODUCTION Apps Script project");
  }
}

function transform(name, text, testId) {
  if (!name.endsWith(".js")) return text;
  return text
    .split(PRODUCTION_SPREADSHEET_ID).join(testId)
    .replace(/SpreadsheetApp\.openById\(/g, "pandaTestSpreadsheet_(");
}

function verify(files) {
  const problems = [];
  Object.entries(files).forEach(([name, text]) => {
    if (text.includes(PRODUCTION_SPREADSHEET_ID)) problems.push(name + " contains the production spreadsheet id");
    if (text.includes(PRODUCTION_SCRIPT_ID)) problems.push(name + " contains the production script id");
    if (/openById|openByUrl|SpreadsheetApp\.create|DriveApp|UrlFetchApp/.test(text)) {
      problems.push(name + " uses a service that can reach another spreadsheet or the network");
    }
  });
  const manifest = JSON.parse(files["appsscript.json"]);
  if (JSON.stringify(manifest.oauthScopes) !== JSON.stringify(MANIFEST.oauthScopes)) {
    problems.push("manifest scopes are not exactly spreadsheets.currentonly");
  }
  if (problems.length) throw new Error("Test build failed isolation checks:\n- " + problems.join("\n- "));
}

function build(config, outDir) {
  validateConfig(config);
  const files = {};
  FILES.forEach(name => {
    files[name] = transform(name, fs.readFileSync(path.join(SOURCE, name), "utf8"), config.spreadsheetId);
  });
  files["TestGuard.js"] = guardSource(config.spreadsheetId);
  files["appsscript.json"] = JSON.stringify(MANIFEST, null, 2) + "\n";
  verify(files);

  if (outDir) {
    fs.mkdirSync(outDir, { recursive: true });
    Object.entries(files).forEach(([name, text]) => fs.writeFileSync(path.join(outDir, name), text));
    if (config.scriptId) {
      const clasp = {
        scriptId: config.scriptId,
        rootDir: "",
        parentId: config.spreadsheetId,
        scriptExtensions: [".js", ".gs"],
        htmlExtensions: [".html"],
        jsonExtensions: [".json"],
        filePushOrder: [],
        skipSubdirectories: false
      };
      fs.writeFileSync(path.join(outDir, ".clasp.json"), JSON.stringify(clasp, null, 2) + "\n");
    }
  }
  return files;
}

if (require.main === module) {
  const args = process.argv.slice(2);
  const opt = name => {
    const i = args.indexOf(name);
    return i === -1 ? null : args[i + 1];
  };
  const configPath = path.resolve(opt("--config") || path.join(ROOT, "config", "test.local.json"));
  const outDir = path.resolve(opt("--out") || path.join(ROOT, "build", "test"));
  try {
    const files = build(readConfig(configPath), outDir);
    console.log("Built " + Object.keys(files).length + " files into " + path.relative(ROOT, outDir) + " (isolation checks passed)");
  } catch (error) {
    console.error(error.message);
    process.exit(1);
  }
}

module.exports = { build, transform, verify, validateConfig, guardSource, MANIFEST, PRODUCTION_SPREADSHEET_ID, PRODUCTION_SCRIPT_ID };
