#!/usr/bin/env node
// Builds apps-script/ClientLib.html: the browser bundle included by Index.html.
// Stats.js is shared with the server; Insights.js and App.js are browser-only
// and never exist as server files.
//
// Usage: node tools/build_client.js [--check]

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const SOURCES = ["apps-script/Stats.js", "client/Insights.js", "client/App.js"];
const OUT = path.join(ROOT, "apps-script", "ClientLib.html");

function render() {
  const parts = SOURCES.map(rel => {
    const text = fs.readFileSync(path.join(ROOT, rel), "utf8");
    if (/<\/script/i.test(text) || text.includes("<!--")) {
      throw new Error(rel + " contains a sequence that would break out of the inline <script> element");
    }
    return "// ---- " + rel + " ----\n" + text.trim() + "\n";
  });
  return "<!-- GENERATED by tools/build_client.js. Do not edit; edit the sources and rebuild. -->\n" +
    "<script>\n" + parts.join("\n") + "</script>\n";
}

if (require.main === module) {
  const html = render();
  if (process.argv.includes("--check")) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
    if (current !== html) {
      console.error("apps-script/ClientLib.html is stale. Run: node tools/build_client.js");
      process.exit(1);
    }
    console.log("ClientLib.html is up to date.");
  } else {
    fs.writeFileSync(OUT, html);
    console.log("Wrote " + path.relative(ROOT, OUT) + " (" + html.length + " bytes)");
  }
}

module.exports = { render, OUT, SOURCES };
