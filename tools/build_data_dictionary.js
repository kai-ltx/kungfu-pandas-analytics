"use strict";

// Generates docs/pandametrics-data-dictionary.md from the Stats.js registry.
//   node tools/build_data_dictionary.js

const fs = require("node:fs");
const path = require("node:path");
const { loadStats } = require("../tests/js/load");

const OUT = path.join(__dirname, "..", "docs", "pandametrics-data-dictionary.md");

const STORED_FIELDS = [
  ["matchId", "Match", "EA match id, kept as a digit string (text cell) so 16+ digit ids are not rounded. Key with clubId.", "verified"],
  ["clubId", "Match/appearance", "Our club id. Key with matchId (+ playerId).", "verified"],
  ["playerId", "Appearance", "EA player id. Stable across all three clubs in Nov 2026 samples; used to merge profiles.", "verified"],
  ["timestamp", "Match/appearance", "Kick-off time as ISO-8601 in Europe/London.", "verified"],
  ["timestampUnix", "Match", "Kick-off time as Unix seconds (V4 rows only).", "verified"],
  ["matchType", "Match/appearance", "leagueMatch or playoffMatch. Friendlies are never imported.", "verified"],
  ["eaMatchTypeCode", "Match", "EA clubs[*].matchType code: \"1\" league, \"3\" playoff (observed).", "verified"],
  ["result / goals / goalsAgainst", "Match", "From EA wins/losses/ties flags, falling back to score.", "verified"],
  ["dnf", "Match", "A club quit and the other was awarded the win.", "verified"],
  ["position", "Appearance", "EA pos for this match: forward, midfielder, defender or goalkeeper. Group only; exact positions are not in the API.", "verified"],
  ["positionGroup", "Appearance", "ATT / MID / DEF / GK derived from position.", "verified"],
  ["archetypeId", "Appearance", "EA archetype id for this match (1-13 observed). No verified id-to-name mapping.", "experimental"],
  ["secondsPlayed", "Appearance", "EA game-clock seconds. Identical for every player in 59 of 66 sampled line-ups (usually match length); lower for late joiners. Used for per-90.", "medium"],
  ["realTimeSeconds", "Appearance", "EA realtimegame (wall-clock seconds).", "verified"],
  ["rating", "Appearance", "EA match rating.", "verified"],
  ["rawEvents", "Appearance", "All decoded-or-not event counters as sorted id:count pairs. Lossless; allows future remapping.", "verified"],
  ["eventCoverage", "Appearance", "complete / missing (no events) / incomplete (truncated: event passes < 50% of EA pass attempts).", "verified"],
  ["eventsAvailable", "Appearance", "true only when eventCoverage is complete. Event stats are blank (not 0) otherwise.", "verified"],
  ["appearanceStatus", "Appearance", "played / did_not_play (0 seconds, 0 real time, no events). did_not_play rows are not appearances.", "verified"],
  ["dataQualityFlags", "Match/appearance", "Semicolon list: eventsMissing, eventsIncomplete, didNotPlay, unknownPosition, goalsMismatch, passTotalsMissing, dnf, matchTypeCode:N.", "verified"],
  ["eventGoals / eventAssists / eventShots", "Appearance", "Event-decoded values kept beside EA named goals/assists/shots to expose discrepancies.", "high"]
];

function render() {
  const S = loadStats();
  const lines = [];
  lines.push("# PandaMetrics Data Dictionary");
  lines.push("");
  lines.push("_Generated by `node tools/build_data_dictionary.js` from `apps-script/Stats.js`. Do not edit by hand._");
  lines.push("");
  lines.push("**Confidence:** `verified` = EA named field; `high` = community-confirmed event mapping ([research](https://github.com/Interactive-63/eafc-pro-clubs-api-research), decoded by fc-clubs-api 0.3.0); `medium` = derived or caveated; `experimental` = shown with a warning, never used in scores.");
  lines.push("");
  lines.push("**Aggregation rules:** one appearance per club + match + player; `did_not_play` rows excluded; event metrics skip rows whose events are missing or incomplete (missing is not zero); ratios pool numerator and denominator across matches; per 90 = total ÷ secondsPlayed × 5400 and only when every included row has seconds.");
  lines.push("");
  lines.push("## Stored fields");
  lines.push("");
  lines.push("| Field | Level | Meaning | Confidence |");
  lines.push("|---|---|---|---|");
  STORED_FIELDS.forEach(([f, level, meaning, conf]) => lines.push(`| \`${f}\` | ${level} | ${meaning} | ${conf} |`));
  lines.push("");
  lines.push("## Metrics");
  lines.push("");

  Object.entries(S.CATEGORIES).forEach(([cat, catLabel]) => {
    const metrics = S.METRICS.filter(m => m.category === cat);
    if (!metrics.length) return;
    lines.push(`### ${catLabel}`);
    lines.push("");
    lines.push("| Key | Label | Type | Formula | Better | Min attempts | Source | Confidence | Notes |");
    lines.push("|---|---|---|---|---|---|---|---|---|");
    metrics.forEach(m => {
      const better = m.higherIsBetter === null ? "context" : m.higherIsBetter ? "higher" : "lower";
      const notes = [m.description, m.overlap].filter(Boolean).join(" ").replace(/\|/g, "/");
      lines.push(`| \`${m.key}\` | ${m.label} | ${m.type} | \`${S.formula(m)}\` | ${better} | ${m.minAttempts || "-"} | ${m.source} | ${m.confidence} | ${notes} |`);
    });
    lines.push("");
  });

  lines.push("## Panda Score role weights");
  lines.push("");
  lines.push("Each appearance is scored against appearances in the same position group: every weighted metric becomes a percentile (inverted for lower-is-better), then a weighted mean. Counts use per 90 with a 20-minute floor; ratios are shrunk towards the role's pooled rate by `shrinkage` attempts. An appearance needs " +
    Math.round(S.SCORE_SETTINGS.minWeightCoverage * 100) + "% of its role's weight to be scored. Roles with fewer than " +
    S.SCORE_SETTINGS.minBenchmarkAppearances + " appearances benchmark against all appearances. A player's score is the mean of their appearance scores. EA match rating is excluded.");
  lines.push("");
  lines.push("| Role | Metric weights |");
  lines.push("|---|---|");
  Object.entries(S.ROLE_WEIGHTS).forEach(([g, w]) => {
    lines.push(`| ${S.GROUP_LABELS[g]} (${g}) | ${Object.entries(w).map(([k, v]) => `${S.getMetric(k).label} ×${v}`).join(", ")} |`);
  });
  lines.push("");
  lines.push("## Experimental events");
  lines.push("");
  lines.push("These four community mappings are copied off `rawEvents` as counts and shown with an experimental badge. A row with no raw log leaves them blank. They are never used in the Panda Score or awards.");
  lines.push("");
  lines.push("| Event | Field | Meaning |");
  lines.push("|---|---|---|");
  Object.entries(S.EXPERIMENTAL_FIELDS).forEach(([id, field]) => {
    const metric = S.METRICS.find(m => m.fields && m.fields[0] === field);
    lines.push(`| ${id} | \`${field}\` | ${metric.description.replace(/\|/g, "/")} |`);
  });
  lines.push("");
  lines.push("## Not available from the API");
  lines.push("");
  lines.push("- Exact position per match (only the group).");
  lines.push("- Archetype names for `archetypeId`, PlayStyles, attribute allocations, portraits.");
  lines.push("- Lost aerial duels (so no aerial success rate), xG/xA, distance, metres progressed, pressing.");
  lines.push("- Goalkeeper appearances: none in samples (AI keepers).");
  lines.push("");
  return lines.join("\n");
}

module.exports = { render, OUT };

if (require.main === module) {
  fs.writeFileSync(OUT, render());
  console.log("wrote " + path.relative(process.cwd(), OUT));
}
